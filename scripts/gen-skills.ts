/* Bundles hub/skills/<name>/SKILL.md into src/lib/hub/skills.generated.ts (Workers have no filesystem).
   Run after editing a skill: npx tsx scripts/gen-skills.ts */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(process.cwd(), "hub", "skills");
const skills: Record<string, string> = {};
for (const name of readdirSync(root, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
  skills[name] = readFileSync(join(root, name, "SKILL.md"), "utf8");
}
const body = `/* GENERATED by scripts/gen-skills.ts from the SKILL.md files under hub/skills. Do not edit. */
export const SKILLS: Record<string, string> = ${JSON.stringify(skills, null, 2)};

const BY_TOPIC: Record<string, string> = {
  fingerprints: "residence-card-fingerprints",
  wezwanie: "letters-wezwanie",
  doctor: "doctor-registration",
  bank: "bank-account",
};

export function skillFor(topics: string[]): string | undefined {
  const name = topics.map((t) => BY_TOPIC[t]).find((n) => n && SKILLS[n]);
  return name ? SKILLS[name] : undefined;
}
`;
writeFileSync(join(process.cwd(), "src", "lib", "hub", "skills.generated.ts"), body);
process.stdout.write(`bundled ${Object.keys(skills).length} skills\n`);
