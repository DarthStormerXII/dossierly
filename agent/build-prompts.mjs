// Bundles agent/prompts/*.md into src/lib/agent/prompt-text.ts so the Worker fallback uses the
// same prompt contract as the sandbox. Run: node agent/build-prompts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = {};
for (const kind of ["prepare", "ask", "file"]) out[kind] = readFileSync(join(root, "agent/prompts", `${kind}.md`), "utf8").trim();
writeFileSync(
  join(root, "src/lib/agent/prompt-text.ts"),
  `// Generated by agent/build-prompts.mjs from agent/prompts/*.md. Do not edit.\nexport const PROMPT_TEXT = ${JSON.stringify(out, null, 2)} as const;\n`,
);
