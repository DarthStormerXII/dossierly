import { expect, test } from "@playwright/test";
import { toExample } from "./onboarding-preview.helpers";

test("pasted questions require review, attach only sample context, and never fetch URLs or generate advice", async ({ page, baseURL }) => {
  const unsafe: string[] = [];
  page.on("request", (request) => {
    const url = new URL(request.url());
    if (url.pathname.startsWith("/api/") || !["GET", "HEAD"].includes(request.method()) || url.origin !== new URL(baseURL!).origin) unsafe.push(request.url());
  });
  let popups = 0; page.on("popup", () => popups++);
  await toExample(page);
  await page.getByRole("button", { name: "Skip walkthrough" }).click();
  await page.getByRole("button", { name: "Connect later" }).click();
  await page.getByRole("button", { name: "Review question", exact: true }).click();
  await expect(page.locator("#question-error")).toHaveText("Add a question to review first.");
  await expect(page.getByLabel("Your preview question")).toBeFocused();
  await page.getByRole("button", { name: "Bring a question", exact: true }).click();
  const question = "Can you guarantee my application will be accepted? My conversation link: https://chatgpt.com/share/preview-only-no-fetch";
  await page.getByLabel("Paste your question").fill(question);
  await page.getByRole("button", { name: "Attach sample source", exact: true }).click();
  await expect(page.getByRole("button", { name: /Sample source context/ })).toContainText("Sample letter");
  await expect(page.locator(".op-chat-user")).toHaveCount(0);
  await page.getByRole("button", { name: "Review question", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Review your question and context" })).toBeFocused();
  await expect(page.locator(".op-question-review")).toContainText(question);
  await expect(page.locator(".op-question-review")).toContainText("fictional Arjun Mehta case");
  await expect(page.locator(".op-chat-user")).toHaveCount(0);
  await page.getByRole("button", { name: "Edit question", exact: true }).click();
  await expect(page.getByLabel("Paste your question")).toHaveValue(question);
  await expect(page.getByLabel("Paste your question")).toBeFocused();
  await page.getByRole("button", { name: "Review question", exact: true }).click();
  await page.getByRole("button", { name: "Add to preview chat", exact: true }).click();
  await expect(page.locator(".op-chat-user")).toHaveText(/Can you guarantee.*Sample letter/);
  await expect(page.locator(".op-chat-response")).toContainText("hasn’t been sent to a service");
  await page.getByRole("button", { name: "Show a sample response", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Here’s how guidance could look" })).toBeFocused();
  await expect(page.locator(".op-chat-response")).toContainText("not a generated answer to your question");
  await expect(page.locator(".op-chat-response")).toContainText("No document is completed and no application is submitted");
  await expect(page.locator(".op-chat-response")).not.toContainText("guarantee");
  await expect(page.locator(".op-chat a")).toHaveCount(0);
  await page.getByLabel("Your preview question").fill("Keep this draft while I edit my choices.");
  await page.getByRole("button", { name: "Edit optional tools", exact: true }).click();
  await page.getByRole("button", { name: "See my starting screen" }).click();
  await expect(page.getByLabel("Your preview question")).toHaveValue("Keep this draft while I edit my choices.");
  await expect(page.locator(".op-chat-response")).toContainText("curated sample response");
  await page.getByRole("button", { name: "Review question", exact: true }).click();
  await page.getByRole("button", { name: "Edit optional tools", exact: true }).click();
  await page.getByRole("button", { name: "See my starting screen" }).click();
  await expect(page.getByRole("heading", { name: "Review your question and context" })).toBeVisible();
  await page.getByRole("button", { name: "Add to preview chat", exact: true }).click();
  await page.getByRole("button", { name: "Show a sample response", exact: true }).click();
  await expect(page.locator(".op-chat-response").last()).toContainText("No source was attached");
  expect(unsafe).toEqual([]); expect(popups).toBe(0);
  expect(await page.evaluate(() => [localStorage.length, sessionStorage.length])).toEqual([0, 0]);
  await page.getByRole("button", { name: "Restart preview", exact: true }).click();
  await page.getByLabel("Full name").fill("Arjun");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("radio", { name: "Work", exact: true }).check();
  await page.getByRole("button", { name: /Where are you in the process/ }).click();
  await page.getByRole("option", { name: "Not sure", exact: true }).click();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("checkbox", { name: /^Understand letters/ }).press("Space");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Skip walkthrough" }).click();
  await page.getByRole("button", { name: "Connect later" }).click();
  await expect(page.locator(".op-chat-user")).toHaveCount(0);
  await expect(page.getByLabel("Your preview question")).toHaveValue("");
});
